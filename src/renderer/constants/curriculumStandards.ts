export function getStandardsByGrade(gradeLabel: string): GradeGroupStandards | undefined {
  return CURRICULUM_STANDARDS.find(g => g.grades.includes(gradeLabel));
}

export function getSubjectsForGradeStandards(gradeLabel: string): string[] {
  return getStandardsByGrade(gradeLabel)?.subjects ? Object.keys(getStandardsByGrade(gradeLabel)!.subjects) : [];
}

export function getStandards(gradeLabel: string, subject: string): AchievementStandard[] {
  return getStandardsByGrade(gradeLabel)?.subjects[subject] ?? [];
}
